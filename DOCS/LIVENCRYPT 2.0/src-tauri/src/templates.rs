fn templates_dir() -> std::path::PathBuf {
    crate::livencrypt_base_dir()
        .join(".livencrypt")
        .join("templates")
}

#[tauri::command]
pub fn get_templates_dir(_app: AppHandle) -> Result<String, String> {
    let path = templates_dir();

    if !path.exists() {
        fs::create_dir_all(&path).map_err(|e| e.to_string())?;
    }

    Ok(path.to_string_lossy().into_owned())
}

#[tauri::command]
pub fn load_templates(_app: AppHandle) -> Result<HashMap<String, TemplateData>, String> {
    if let Some(templates) = crate::security::try_load_unlocked_templates()? {
        return Ok(templates
            .into_iter()
            .map(|(name, data)| (name, normalize_template_data(data)))
            .collect());
    }

    let dir_path = templates_dir();

    let mut templates = HashMap::new();

    if dir_path.exists() {
        for entry in fs::read_dir(dir_path).map_err(|e| e.to_string())? {
            if let Ok(entry) = entry {
                let path = entry.path();
                if path.extension().and_then(|s| s.to_str()) == Some("msgpack") {
                    if let Ok(content) = fs::read(&path) {
                        if let Ok(data) = rmp_serde::from_slice::<TemplateData>(&content) {
                            let file_name = path
                                .file_stem()
                                .unwrap_or_default()
                                .to_string_lossy()
                                .into_owned();
                            templates.insert(file_name, normalize_template_data(data));
                        }
                    }
                }
            }
        }
    }
    Ok(templates)
}

