#[tauri::command]
pub fn initialize_defaults(app: AppHandle) -> Result<(), String> {
    if crate::security::vault_is_configured() {
        return Ok(());
    }

    let dir_path = templates_dir();

    if !dir_path.exists() {
        fs::create_dir_all(&dir_path).map_err(|e| e.to_string())?;
    }

    for legacy_name in [
        "Plantilla_1",
        "Plantilla_2",
        "Plantilla_3",
        "Plantilla_4",
        "Plantilla_5",
        "filelivencrypt",
    ] {
        let legacy_path = dir_path.join(format!("{}.msgpack", legacy_name));
        if legacy_path.exists() {
            fs::remove_file(&legacy_path).map_err(|e| {
                format!("Error al eliminar plantilla legacy {}: {}", legacy_name, e)
            })?;
        }
    }

    if !dir_path.join("Livencrypt.msgpack").exists() {
        save_template(app, "Livencrypt".to_string(), filelivencrypt_template())?;
    }

    Ok(())
}

#[tauri::command]
pub fn save_template(_app: AppHandle, name: String, data: TemplateData) -> Result<(), String> {
    let data = normalize_template_data(data);

    if crate::security::save_template_to_unlocked_vault(name.clone(), data.clone())? {
        return Ok(());
    }

    let dir_path = templates_dir();
    fs::create_dir_all(&dir_path)
        .map_err(|e| format!("Error al crear directorio de plantillas: {}", e))?;

    let file_path = dir_path.join(format!("{}.msgpack", name));

    let encoded_data = rmp_serde::to_vec(&data)
        .map_err(|e| format!("Error al serializar con MessagePack: {}", e))?;

    fs::write(file_path, encoded_data).map_err(|e| format!("Error de escritura: {}", e))?;

    Ok(())
}

